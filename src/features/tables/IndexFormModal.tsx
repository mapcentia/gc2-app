import { useTranslation } from 'react-i18next';
import { Drawer, Form, Input, Select, Button } from 'antd';

interface Props {
  open: boolean;
  columns: string[];
  onOk: (values: any) => void;
  onCancel: () => void;
  saving?: boolean;
}

export default function IndexFormModal({ open, columns, onOk, onCancel, saving }: Props) {
  const { t } = useTranslation();
  const [form] = Form.useForm();

  const handleOk = async () => {
    const values = await form.validateFields();
    onOk(values);
  };

  return (
    <Drawer title={t('tables.createIndex')} open={open} onClose={onCancel} width={480}
      extra={<Button type="primary" onClick={handleOk} loading={saving}>{t('common.save')}</Button>}
      afterOpenChange={(visible) => { if (!visible) form.resetFields(); }}>
      <Form form={form} layout="vertical" initialValues={{ method: 'btree' }}>
        <Form.Item name="columns"
          // i18n-ignore
          label="Columns" rules={[{ required: true }]}>
          <Select mode="multiple" options={columns.map((c) => ({ label: c, value: c }))} />
        </Form.Item>
        <Form.Item name="method" label={t('tables.method')} rules={[{ required: true }]}>
          <Select options={[
            // i18n-ignore
            { label: 'btree', value: 'btree' },
            // i18n-ignore
            { label: 'brin', value: 'brin' },
            // i18n-ignore
            { label: 'gin', value: 'gin' },
            // i18n-ignore
            { label: 'gist', value: 'gist' },
            // i18n-ignore
            { label: 'hash', value: 'hash' },
          ]} />
        </Form.Item>
        <Form.Item name="name" label={t('tables.indexName')}>
          <Input placeholder={t('tables.optionalAutoGenerated')} />
        </Form.Item>
      </Form>
    </Drawer>
  );
}
